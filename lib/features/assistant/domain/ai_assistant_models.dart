/// Identifies whether an assistant reply came from deterministic rules,
/// optional AI assistance, or an automatic deterministic fallback.
enum AssistantReplySource {
  deterministic(label: 'Deterministic'),
  ai(label: 'AI Assisted'),
  deterministicFallback(label: 'Deterministic Fallback');

  const AssistantReplySource({required this.label});

  final String label;
}

/// Explicit per-user opt-in controls governing optional AI assistance and
/// sensitive data sharing (Phase 9 Security Requirements).
class AiConsentSettings {
  const AiConsentSettings({
    this.aiEnabled = false,
    this.shareFinancialSummary = false,
    this.shareDocumentAlerts = false,
  });

  final bool aiEnabled;
  final bool shareFinancialSummary;
  final bool shareDocumentAlerts;

  AiConsentSettings copyWith({
    bool? aiEnabled,
    bool? shareFinancialSummary,
    bool? shareDocumentAlerts,
  }) {
    return AiConsentSettings(
      aiEnabled: aiEnabled ?? this.aiEnabled,
      shareFinancialSummary:
          shareFinancialSummary ?? this.shareFinancialSummary,
      shareDocumentAlerts: shareDocumentAlerts ?? this.shareDocumentAlerts,
    );
  }

  @override
  bool operator ==(Object other) {
    if (identical(this, other)) {
      return true;
    }
    return other is AiConsentSettings &&
        other.aiEnabled == aiEnabled &&
        other.shareFinancialSummary == shareFinancialSummary &&
        other.shareDocumentAlerts == shareDocumentAlerts;
  }

  @override
  int get hashCode =>
      Object.hash(aiEnabled, shareFinancialSummary, shareDocumentAlerts);
}

/// Per-user daily usage limits and cost-control bounds for Phase 9 AI calls.
class AiUsageQuota {
  const AiUsageQuota({
    required this.usageDate,
    this.usedToday = 0,
    this.dailyLimit = 25,
    this.maxOutputTokens = 512,
    this.estimatedTokensToday = 0,
  });

  final KayaDateOnly usageDate;
  final int usedToday;
  final int dailyLimit;
  final int maxOutputTokens;
  final int estimatedTokensToday;

  int get remainingToday => (dailyLimit - usedToday).clamp(0, dailyLimit);
  bool get isExceeded => usedToday >= dailyLimit;

  AiUsageQuota increment({required int estimatedTokens}) {
    return AiUsageQuota(
      usageDate: usageDate,
      usedToday: usedToday + 1,
      dailyLimit: dailyLimit,
      maxOutputTokens: maxOutputTokens,
      estimatedTokensToday:
          estimatedTokensToday + (estimatedTokens < 0 ? 0 : estimatedTokens),
    );
  }
}

/// Proposed task generated by AI task-planning assistance.
///
/// Security rule (Phase 9): Never written automatically; requires explicit
/// user confirmation before creating a task in [TaskController].
class AiTaskSuggestion {
  const AiTaskSuggestion({
    required this.id,
    required this.title,
    this.priority = TaskPriority.medium,
    this.category = TaskCategory.personal,
    this.dueDate,
    this.isConfirmed = false,
    this.isDismissed = false,
  });

  final String id;
  final String title;
  final TaskPriority priority;
  final TaskCategory category;
  final KayaDateOnly? dueDate;
  final bool isConfirmed;
  final bool isDismissed;

  bool get isPending => !isConfirmed && !isDismissed;

  AiTaskSuggestion copyWith({bool? isConfirmed, bool? isDismissed}) {
    return AiTaskSuggestion(
      id: id,
      title: title,
      priority: priority,
      category: category,
      dueDate: dueDate,
      isConfirmed: isConfirmed ?? this.isConfirmed,
      isDismissed: isDismissed ?? this.isDismissed,
    );
  }
}

/// Privacy-minimized context payload safe to transmit to the server-side AI
/// backend. Excludes user IDs, record IDs, notes, locations, and raw transactions.
class AiMinimizedContextPayload {
  const AiMinimizedContextPayload({
    required this.referenceDateIso,
    required this.taskSummary,
    required this.routineSummary,
    this.financialSummary,
    this.documentAlerts,
  });

  final String referenceDateIso;
  final Map<String, Object?> taskSummary;
  final Map<String, Object?> routineSummary;
  final Map<String, Object?>? financialSummary;
  final Map<String, Object?>? documentAlerts;

  Map<String, Object?> toJson() {
    return <String, Object?>{
      'referenceDate': referenceDateIso,
      'tasks': taskSummary,
      'routines': routineSummary,
      if (financialSummary != null) 'financialSummary': financialSummary,
      if (documentAlerts != null) 'documentAlerts': documentAlerts,
    };
  }

  @override
  String toString() =>
      'AiMinimizedContextPayload(date: $referenceDateIso, '
      'hasFinancial: ${financialSummary != null}, '
      'hasDocuments: ${documentAlerts != null})';
}

/// Request sent to the server-side [AiAssistantGateway].
class AiGatewayRequest {
  const AiGatewayRequest({
    required this.prompt,
    required this.language,
    required this.minimizedContext,
    this.recentHistory = const <Map<String, String>>[],
    this.maxOutputTokens = 512,
  });

  final String prompt;
  final AssistantLanguage language;
  final AiMinimizedContextPayload minimizedContext;
  final List<Map<String, String>> recentHistory;
  final int maxOutputTokens;

  Map<String, Object?> toJson() {
    return <String, Object?>{
      'prompt': prompt,
      'language': language.name,
      'minimizedContext': minimizedContext.toJson(),
      'recentHistory': recentHistory,
      'maxOutputTokens': maxOutputTokens,
    };
  }
}

/// Raw structured response returned from the server-side [AiAssistantGateway]
/// prior to client-side [AiResponseValidator] checks.
class AiGatewayResponse {
  const AiGatewayResponse({
    required this.replyText,
    this.details = const <String>[],
    this.suggestedTasks = const <AiTaskSuggestion>[],
    this.estimatedTokens = 0,
    this.providerLabel = 'KAYA Cloud AI',
  });

  final String replyText;
  final List<String> details;
  final List<AiTaskSuggestion> suggestedTasks;
  final int estimatedTokens;
  final String providerLabel;
}
